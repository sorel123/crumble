/* A deal takes a moment to work out (about 0.1-0.3 s on a laptop, more on an older phone), so the card works out today's
   and the next new one while she reads it, and a button whose deal is not ready says "Dealing…" for that moment. */
let chNext='';
function chPrefetch(){
  clearTimeout(chPrefetch.t);
  chPrefetch.t=setTimeout(()=>{
    if(el('chalCard').hidden) return;
    if(!chCache.has(chToday())){ chDeal(chToday()); chPrefetch(); return; }
    if(!chNext){ chNext=chNewSeed(); chDeal(chNext); }
  },350);
}
function chFresh(){ const s=chNext||chNewSeed(); chNext=''; return s; }
function chReady(seed,btn,go){                      // go() now if the deal is cached, else after "Dealing…" has painted
  if(chCache.has(seed)||!btn) return go();
  const b=btn.querySelector('b')||btn, was=b.textContent; b.textContent='Dealing…';
  setTimeout(()=>{ chDeal(seed); b.textContent=was; go(); },40);
}
function playChal(seed){
  leaveMode(); hideMenus(); mode='challenge'; lvl=null; saveMode();
  const o=peekRun('challenge');
  if(!(o&&o.ch&&(seed===undefined||o.ch.seed===seed)&&loadRun())){ chSeed=seed||chToday(); start(); }   // today's, already under way: carry on
  syncHud();
}

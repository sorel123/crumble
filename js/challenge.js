// Crumble — Challenge mode (1.1 task E): a short round with a finish, a fixed deal and medals.
// Plain script, loaded in order by index.html; shares globals with the other js/ files.
/* ═══════ challenge ═══════
   Twelve trays (36 pieces), no timer. Running out of moves ends it early and the score stands.
   The deal is frozen: the opening board and all twelve trays are worked out up front from the seed and never react
   to her play, so everyone who plays a seed gets the same pieces in the same order (the Daily cannot promise that:
   its trays read her board). To make it a deal with payoffs in it, it is generated by the real dealer (dealSteps,
   with golden hands and transformations off) dealing to the casual bot of tools/bot-sim.mjs, and then frozen.
   While it generates, fairDeal makes the dealer's shuffles engine-independent (shapes.js), so a seed deals the same
   on an iPhone and in Chrome.
   Medals: bronze / silver / gold score targets for that deal, worked out by bots playing the frozen deal with the
   game's own scoring (chDrop mirrors place()'s points): bronze is the median of a noisy casual bot, silver about its
   85th percentile, gold 0.85 x a planner bot (a beam search over each tray, scoring points and room). Shown from the
   first move; the HUD shows the next target and the tray number.
   Seeds: "Today's challenge" is the local date (everyone on a day gets the same one), "New challenge" a random one.
   Unlimited retries, the best counts. Specials: bonus trays and the star stay (a star is part of the deal if the
   dealer dealt one); golden hands and transformations are off (they depend on live dealing). No rescue.
   Saved: the run in `crumble.run.chal` (with its whole deal, so an update to the dealer never changes a round in
   progress) and results in `crumble.chal` = {v:1, s:{"<seed>":{b:best score, m:best medal 0-3, n:plays}}, won, gold}
   (won: challenges with a medal, gold: with gold; counted once per seed, kept when old seeds are pruned). */
const CH_TRAYS=12, CHAL_STORE='crumble.chal', CH_KEEP=60;
const MEDALS=[{name:'Bronze',icon:'🥉',col:'#F0A86A'},{name:'Silver',icon:'🥈',col:'#E4ECF5'},{name:'Gold',icon:'🥇',col:'#FFD45C'}];
let chal=null;           // the round in play: {seed, deal:{open, trays, med}, won: medals reached so far (0-3)}
let chGen=false;         // generating a deal: commitTray only records the hand (solver.js)
let chSeed='';           // the seed the next start() deals
let chDone=false;        // the twelfth tray has been played: the round is over, the end card is on its way
const chalRec={s:{},won:0,gold:0};
const chCache=new Map(); // seed -> deal (with medals), so a retry starts at once

/* ── seeds ── */
const chToday=()=>'d'+dailyKey();
function chNewSeed(){ let s=''; for(let i=0;i<6;i++) s+='abcdefghjkmnpqrstuvwxyz23456789'[(Math.random()*31)|0]; return s; }
const chIsToday=seed=>seed===chToday();
function chLabel(seed){
  if(/^d\d{4}-\d\d-\d\d$/.test(seed)) return chIsToday(seed)?"Today's challenge":'Challenge · '+new Date(seed.slice(1)+'T12:00:00').toLocaleDateString(undefined,{month:'short',day:'numeric'});
  return 'Challenge #'+seed.toUpperCase();
}

/* ── the board as data (bots and scoring): 64 cells, each a gem colour or -1 ── */
const chBits=a=>{ let lo=0,hi=0; for(let i=0;i<32;i++){ if(a[i]>=0) lo|=1<<i; if(a[i+32]>=0) hi|=1<<i; } return [lo,hi]; };
function chState(open){ const a=new Int8Array(64); for(let r=0;r<N;r++) for(let c=0;c<N;c++) a[r*N+c]=open[r][c]; return {a,combo:0,score:0,meter:0,bonus:0,trayNo:1,specialEnd:-99}; }
const chClone=S=>({...S,a:S.a.slice()});
/* One drop, scored exactly as place() scores it (game.js): the piece's cells, lines squared with the combo step, a
   star's per-gem floor, COLOR GONE on a loud clear, the clean-sweep bonus, and x2 while a bonus runs. The bonus meter
   fills the same way (chargeBonus). Golden hands and transformations never happen in a Challenge. Returns lines. */
function chDrop(S,s,gi,r,c){
  const a=S.a; let gained=s.n*SCORE_SCALE, rows=[], cols=[], starGems=0;
  if(s.star){
    for(let k=0;k<N;k++){ if(a[r*N+k]>=0) starGems++; if(a[k*N+c]>=0) starGems++; }
    let rh=false, ch=false; for(let k=0;k<N;k++){ if(a[r*N+k]>=0) rh=true; if(a[k*N+c]>=0) ch=true; }
    if(rh) rows.push(r); if(ch) cols.push(c);
    S.specialEnd=S.trayNo;
  } else {
    for(const [dr,dc] of s.cells) a[(r+dr)*N+c+dc]=gi;
    for(let i=0;i<N;i++){ let fr=true, fc=true; for(let k=0;k<N;k++){ if(a[i*N+k]<0) fr=false; if(a[k*N+i]<0) fc=false; } if(fr) rows.push(i); if(fc) cols.push(i); }
  }
  const total=rows.length+cols.length;
  if(total>0){
    const loud=S.combo+1>=CFG.BIG_COMBO;
    S.combo++;
    if(special('bonus')&&!S.bonus&&S.trayNo>=CFG.SPECIAL_FROM_TRAY&&S.meter<CFG.BONUS_METER)
      S.meter=Math.min(CFG.BONUS_METER,S.meter+total+Math.min(Math.max(S.combo-1,0),CFG.BONUS_COMBO_MAX));
    gained+=Math.round(CFG.LINE_POINTS*total*total*(1+(S.combo-1)*CFG.COMBO_STEP));
    if(s.star) gained=s.n*SCORE_SCALE+Math.max(gained-s.n*SCORE_SCALE,Math.round(CFG.STAR_PER_GEM*starGems*(1+(S.combo-1)*CFG.COMBO_STEP)));
    const before=new Set(); for(let i=0;i<64;i++) if(a[i]>=0) before.add(a[i]);
    let cleared=0;
    const wipe=i=>{ if(a[i]>=0){ a[i]=-1; cleared++; } };
    for(const rr of rows) for(let k=0;k<N;k++) wipe(rr*N+k);
    for(const cc of cols) for(let k=0;k<N;k++) wipe(k*N+cc);
    const after=new Set(); for(let i=0;i<64;i++) if(a[i]>=0) after.add(a[i]);
    const gone=[...before].filter(g=>!after.has(g)).length;
    if(loud&&gone&&after.size>0&&CFG.COLOR_GONE_BONUS>0) gained+=Math.round(CFG.COLOR_GONE_BONUS*gone*(1+(S.combo-1)*0.25));
    if(!after.size) gained+=CFG.SWEEP_BONUS+cleared*CFG.SWEEP_PER_GEM;
  } else S.combo=0;
  if(S.bonus) gained=Math.round(gained*CFG.BONUS_MULT);
  S.score+=gained;
  return total;
}
// the start of tray t (2-12) and the end of a tray, for the bonus: the same rules as bonusDue()/startBonus()/endBonus()
function chTrayIn(S,t,label){
  S.trayNo=t;
  if(t>1&&special('bonus')&&!S.bonus&&S.meter>=CFG.BONUS_METER&&t>=CFG.SPECIAL_FROM_TRAY&&t>S.specialEnd+1){ S.meter=0; S.bonus=CFG.BONUS_TRAYS; }
  if(label==='CLOSER') S.specialEnd=t;
}
function chTrayOut(S){ if(S.bonus&&--S.bonus===0) S.specialEnd=S.trayNo; }
const chFits=(lo,hi,s)=>placeMasks(s).some(m=>!(lo&m.lo)&&!(hi&m.hi));

/* ── the bots ── */
/* casual (tools/bot-sim.mjs): an obvious clear if a piece has one (the one that clears the most lines), else the biggest
   piece where it sits most flush. eps (medal runs only): a player who is not looking that hard. With chance eps she
   misses the obvious clear, takes the pieces in another order, and puts a piece in one of its three most flush spots. */
function chCasual(S,left,rng,eps){
  const [lo,hi]=chBits(S.a), miss=()=>!!eps&&rng()<eps;
  const ob=obviousLines(lo,hi);
  let pick=null, pickL=0;
  if(ob.length&&!miss()) for(const k of left){
    if(k.s.star) continue;
    for(const m of placeMasks(k.s)){
      if((lo&m.lo)||(hi&m.hi)) continue;
      const alo=lo|m.lo, ahi=hi|m.hi;
      let obv=false; for(let j=0;j<ob.length;j+=2) if((alo&ob[j])===ob[j]&&(ahi&ob[j+1])===ob[j+1]){ obv=true; break; }
      if(!obv) continue;
      const l=applyBits(lo,hi,k.s,m); if(l>pickL){ pickL=l; pick=[k,m]; }
    }
  }
  if(pick) return pick;
  const order=left.slice().sort((x,y)=>y.s.n-x.s.n);
  if(miss()) for(let i=order.length-1;i>0;i--){ const j=(rng()*(i+1))|0; [order[i],order[j]]=[order[j],order[i]]; }
  for(const k of order){
    const spots=[];
    for(const m of placeMasks(k.s)){
      if((lo&m.lo)||(hi&m.hi)) continue;
      let f=0;
      for(const [dr,dc] of k.s.cells) for(const [da,db] of [[-1,0],[1,0],[0,-1],[0,1]]){
        const rr=m.r+dr+da, cc=m.c+dc+db;
        if(k.s.cells.some(([x,y])=>x===dr+da&&y===dc+db)) continue;
        if(rr<0||cc<0||rr>=N||cc>=N||S.a[rr*N+cc]>=0) f++;
      }
      spots.push([f,m]);
    }
    if(!spots.length) continue;
    let j=0;                                          // the first of the most flush spots, as the bot-sim's bot takes it
    for(let i=1;i<spots.length;i++) if(spots[i][0]>spots[j][0]) j=i;
    if(miss()){ const top=spots.map((x,i)=>i).sort((x,y)=>spots[y][0]-spots[x][0]||x-y).slice(0,3); j=top[(rng()*top.length)|0]; }
    return [k,spots[j][1]];
  }
  return null;
}
/* planner: a beam search over the pieces left in the tray (every order, every spot), each line of play scored on the
   points it makes (chDrop) plus the room it leaves (roomBits, as the strong bot does) and ruled out if it strands a
   piece. jit: a little noise on the scores, so runs differ. Returns the first drop of the best line. */
function chPlanner(S,left,rng,jit){
  let beam=[{S,left,first:null,v:0}], best=null;
  const s0=S.score;
  while(beam.length&&beam[0].left.length){
    const next=[];
    for(const st of beam){
      const [lo,hi]=chBits(st.S.a);
      for(const k of st.left) for(const m of placeMasks(k.s)){
        if((lo&m.lo)||(hi&m.hi)) continue;
        const S2=chClone(st.S); chDrop(S2,k.s,k.gi,m.r,m.c);
        const left=st.left.filter(x=>x!==k), [l2,h2]=chBits(S2.a);
        let v=(S2.score-s0)/SCORE_SCALE+roomBits(l2,h2)*40+(jit?rng()*jit:0);
        if(left.some(x=>!chFits(l2,h2,x.s))) v-=1e5;
        next.push({S:S2,left,first:st.first||[k,m],v});
      }
    }
    if(!next.length) break;
    next.sort((x,y)=>y.v-x.v);
    beam=next.slice(0,8);
    best=beam[0];
  }
  return best?best.first:null;
}
/* one bot run through a frozen deal; returns the score (a stuck bot ends the round early, as she would) */
function chRun(deal,bot,rng,arg){
  const S=chState(deal.open);
  for(let t=0;t<deal.trays.length;t++){
    const T=deal.trays[t]; chTrayIn(S,t+1,T.l);
    let left=T.p.map(([si,gi])=>({s:si<0?STAR:SHAPES[si],gi}));
    while(left.length){
      const mv=bot(S,left,rng,arg); if(!mv) return S.score;
      chDrop(S,mv[0].s,mv[0].gi,mv[1].r,mv[1].c); left=left.filter(x=>x!==mv[0]);
    }
    chTrayOut(S);
  }
  return S.score;
}
const chQ=(a,f)=>{ const b=a.slice().sort((x,y)=>x-y); return b[Math.min(b.length-1,Math.floor((b.length-1)*f+0.5))]; };
const chRound=n=>Math.max(SCORE_SCALE,Math.round(n/(5*SCORE_SCALE))*5*SCORE_SCALE);   // targets in steps of 50 points
/* bronze: the median of CH_CASUAL_RUNS casual runs with a little inattention (CH_CASUAL_EPS); silver: their 85th
   percentile; gold: the second best of the strong runs (the planner's runs and the casual bot's own line, the one the
   deal was dealt to), so a bot reached it at least twice and one lucky run does not set it. Each at least CH_STEP above the one below. The bots' dice are seeded by the seed: the same targets on
   every phone. Measured on ten seeds: bronze 1,300-8,500, gold 4,400-11,600; a planner that only looks at its own
   tray does not beat the casual line by much, because the deal was dealt to that line. */
function chMedals(deal,seed){
  const rng=mulberry(hashStr('crumble-medals-'+seed));
  const cas=[]; for(let i=0;i<CH_CASUAL_RUNS;i++) cas.push(chRun(deal,chCasual,rng,CH_CASUAL_EPS));
  const top=[chRun(deal,chCasual,rng,0)]; for(let i=0;i<CH_PLANNER_RUNS;i++) top.push(chRun(deal,chPlanner,rng,i?6:0));
  const b=chRound(chQ(cas,0.5)), s=chRound(Math.max(chQ(cas,0.85),b*CH_STEP)), g=chRound(Math.max(chQ(top,2/3),s*CH_STEP));
  return [b,s,g];
}
const CH_CASUAL_RUNS=24, CH_CASUAL_EPS=0.15, CH_PLANNER_RUNS=3, CH_STEP=1.2;

/* ── the frozen deal ── */
// the dealer's state, as a new run starts it (flow.js start()): a deal is generated from exactly this, every time
function chResetDealer(){
  grid=empty(); tray=[null,null,null]; trayNo=0; combo=0; carry=[];
  pace={ph:'calm',n:0,hold:0,len:0}; roomNow=1; tension=0; sweepCool=0; specialEnd=-99; resetWave();
  golden=null; goldenNext=false; goldenCool=0; trayHadSweep=false; trayCombo=0; starForced=false; starCool=0;
  transform=null; transformCool=0; bonus=null; bonusMeter=0;
}
/* The deal for a seed: the real dealer deals twelve trays to the casual bot (no noise), told about every drop the way
   place() tells it (waveAfterDrop), and the hands are written down. Returns {open:[8][8] gem or -1, trays:[{p:[[shape
   index or -1 for the star, gem]x3], l:label}], med:[bronze, silver, gold]}. */
// everything the generator touches, so working out a deal (the card prefetches one) never disturbs a run in progress
function chKeep(){
  return {mode,lvl,grid,tray,trayNo,combo,carry,pace,roomNow,tension,sweepCool,specialEnd,wave,jack,setups,closerNext,closerCool,dryN,
    bigHist,closerTray,trayClear,golden,goldenNext,goldenCool,trayHadSweep,trayCombo,starForced,starCool,transform,transformCool,
    bonus,bonusMeter,lastTier,rndSrc,openingKind,ws:{...waveStats}};
}
function chPut(k){
  ({mode,lvl,grid,tray,trayNo,combo,carry,pace,roomNow,tension,sweepCool,specialEnd,wave,jack,setups,closerNext,closerCool,dryN,
    bigHist,closerTray,trayClear,golden,goldenNext,goldenCool,trayHadSweep,trayCombo,starForced,starCool,transform,transformCool,
    bonus,bonusMeter,lastTier,rndSrc,openingKind}=k);
  Object.assign(waveStats,k.ws);
}
function chMake(seed){
  const kept=chKeep(); mode='challenge'; lvl=null;
  chGen=true; fairDeal=true; rndSrc=mulberry(hashStr('crumble-challenge-'+seed));
  try{
    chResetDealer();
    seedOpening();
    const open=grid.map(r=>r.map(g=>g?g.gi:-1));
    const hand=()=>({p:tray.map(t=>[t.s.star?-1:SHAPES.indexOf(t.s),t.gi]),l:lastTier});
    const trays=[hand()];
    const S=chState(open);
    for(let t=1;t<CH_TRAYS;t++){
      S.trayNo=t;
      let left=tray.map(t=>({s:t.s,gi:t.gi}));
      while(left.length){
        let mv=chCasual(S,left,null,0)||chPlanner(S,left,null,0);   // the casual bot; where it sees nothing, the planner finds the way
        if(!mv) break;                                               // stuck: the dealer deals the next tray to the board as it is
        const before=packGrid(grid), roomBefore=roomOf(before);
        const lines=chDrop(S,mv[0].s,mv[0].gi,mv[1].r,mv[1].c);
        combo=S.combo; left=left.filter(x=>x!==mv[0]);
        if(mv[0].s.star) specialEnd=trayNo;                          // what place() tells the dealer about a drop
        if(lines&&special('star')&&combo>=CFG.STAR_COMBO) starForced=true;
        grid=Array.from({length:N},(_,r)=>Array.from({length:N},(_,c)=>S.a[r*N+c]>=0?{gi:S.a[r*N+c],t:1,f:0,l:0}:null));
        waveAfterDrop(before,lines,countFlat(packGrid(grid)),combo,roomBefore<CFG.ROOM_EDGE);
      }
      tray=[null,null,null];
      runSteps(dealSteps());
      trays.push(hand());
    }
    const deal={open,trays};
    deal.med=chMedals(deal,seed);
    return deal;
  } finally { chGen=false; fairDeal=false; chPut(kept); }
}
function chDeal(seed){
  let d=chCache.get(seed);
  if(!d){ d=chMake(seed); chCache.set(seed,d); if(chCache.size>8) chCache.delete(chCache.keys().next().value); }
  return d;
}
function validDeal(d){
  return !!(d&&Array.isArray(d.open)&&d.open.length===N&&d.open.every(r=>Array.isArray(r)&&r.length===N&&r.every(v=>isInt(v,-1,GEMS.length-1)))
    &&Array.isArray(d.trays)&&d.trays.length===CH_TRAYS&&d.trays.every(t=>t&&typeof t.l==='string'&&Array.isArray(t.p)&&t.p.length===3
      &&t.p.every(x=>Array.isArray(x)&&isInt(x[0],-1,SHAPES.length-1)&&isInt(x[1],0,GEMS.length-1)))
    &&Array.isArray(d.med)&&d.med.length===3&&d.med.every(v=>isInt(v,0,1e9)));
}

/* ── playing it ── */
// openBoard() (modes.js), from start(): the round's opening board and first tray
function chOpen(){
  const seed=chSeed||chToday(), deal=chDeal(seed);
  chResetDealer();
  grid=deal.open.map(r=>r.map(gi=>gi<0?null:{gi,t:1,f:0,l:0}));
  chal={seed,deal,won:0}; chDone=false;
  trayNo=1; chCommit(deal.trays[0]);
  pushBanner('CHALLENGE',CH_TRAYS+' trays · '+MEDALS[0].icon+' '+deal.med[0].toLocaleString(),'#FFE9A8');
}
function chCommit(T){
  commitTray(T.p.map(([si])=>si<0?STAR:SHAPES[si]),T.l);
  tray.forEach((t,i)=>{ t.gi=T.p[i][1]; });
}
// dealSteps(), between trays: the next frozen hand, or the end of the round
function chDealNext(){
  if(!chal) return;
  if(trayNo>CH_TRAYS){                               // the twelfth tray is played: the round is over
    trayNo=CH_TRAYS; chDone=true; tray=[null,null,null];
    const m=chMedalOf(score,chal.deal.med);
    pushBanner('ROUND DONE',m?MEDALS[m-1].icon+' '+MEDALS[m-1].name:'','#FFE9A8');
    setTimeout(()=>{ if(chDone&&state==='play'&&mode==='challenge') gameOver(); },reduce?300:1100);
    return;
  }
  if(bonusDue()) startBonus();                       // bonus trays work as anywhere: her clears fill the meter
  chCommit(chal.deal.trays[trayNo-1]);
  if(chal.deal.trays[trayNo-1].l==='CLOSER') specialEnd=trayNo;   // the same special spacing the live dealer keeps after a closer
  roomNow=roomOf(packGrid(grid));
  chHud();
}
// goalStep(), after every drop: a medal she has just reached
function chStep(){
  if(!chal) return;
  const m=chMedalOf(score,chal.deal.med);
  if(m>chal.won){
    chal.won=m; const M=MEDALS[m-1];
    pushBanner(M.name.toUpperCase()+'!',m<3?'Next: '+MEDALS[m].icon+' '+chal.deal.med[m].toLocaleString():'Top medal','#FFE9A8');
    if(!reduce&&m===3) spawnConfetti();
    Sfx.fanfare();
  }
  chHud();
}
const chMedalOf=(sc,med)=>sc>=med[2]?3:sc>=med[1]?2:sc>=med[0]?1:0;
// the HUD: the right box holds the next medal and its target; under the score, the tray number
// and a slim bar under it filling toward the next medal, in that medal's colour (DOM; it writes only on a change)
let chHudKey='';
function chHud(){
  const box=el('chalInfo'); if(!box) return;
  const on=mode==='challenge'&&!!chal;
  if(box.hidden===on) box.hidden=!on;
  if(!on){ chHudKey=''; return; }
  const med=chal.deal.med, m=chMedalOf(score,med), lo=m?med[m-1]:0, f=m>=3?1:clamp((score-lo)/(med[m]-lo),0,1);
  const txt='Tray '+Math.min(trayNo,CH_TRAYS)+' of '+CH_TRAYS, q=Math.round(f*100)/100, key=txt+'|'+q+'|'+m;
  if(key===chHudKey) return;
  chHudKey=key;
  box.querySelector('.to').textContent=txt;
  box.style.setProperty('--mc',MEDALS[Math.min(m,2)].col);
  box.querySelector('.fill').style.transform='scaleX('+q+')';
}
function chHudRight(){                               // syncHud(): [label, value]
  const m=chMedalOf(score,chal.deal.med);
  if(m>=3) return [MEDALS[2].icon+' Gold','Got it!'];
  return [MEDALS[m].icon+' '+MEDALS[m].name,chal.deal.med[m].toLocaleString()];
}

/* ── results ── */
function loadChal(){
  try{
    const o=JSON.parse(localStorage.getItem(CHAL_STORE)||'{}');
    if(o&&o.s&&typeof o.s==='object') for(const k in o.s){ const r=o.s[k]; if(!r||!/^[\w-]{1,24}$/.test(k)) continue;
      chalRec.s[k]={b:isInt(r.b,0,1e9)?r.b:0,m:isInt(r.m,0,3)?r.m:0,n:isInt(r.n,0,1e6)?r.n:0,t:isInt(r.t,0,1e15)?r.t:0}; }
    if(o&&isInt(o.won,0,1e6)) chalRec.won=o.won;
    if(o&&isInt(o.gold,0,1e6)) chalRec.gold=o.gold;
  }catch(e){}
}
function saveChal(){
  const keys=Object.keys(chalRec.s);
  if(keys.length>CH_KEEP){ keys.sort((a,b)=>chalRec.s[a].t-chalRec.s[b].t).slice(0,keys.length-CH_KEEP).forEach(k=>{ delete chalRec.s[k]; }); }
  try{ localStorage.setItem(CHAL_STORE,JSON.stringify({v:1,s:chalRec.s,won:chalRec.won,gold:chalRec.gold})); }catch(e){}
}
function recordChal(seed,sc,med){
  const r=chalRec.s[seed]||(chalRec.s[seed]={b:0,m:0,n:0,t:0}), m=chMedalOf(sc,med), prevB=r.b, prevM=r.m;
  r.n++; r.t=Date.now(); r.b=Math.max(r.b,sc); r.m=Math.max(r.m,m);
  if(prevM<1&&m>=1) chalRec.won++;
  if(prevM<3&&m>=3) chalRec.gold++;
  saveChal();
  return {r,m,prevB,prevM};
}
// gameOver() (flow.js): the end card for a round, finished or out of moves
